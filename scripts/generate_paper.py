doc.add_paragraph(
    'Given a sequence of CDM observations X = {x_1, x_2, ..., x_T} where T = 25 timesteps and each x_t is a '
    '14-dimensional feature vector, the task is to predict y in {0, 1} where y = 1 indicates a high-risk '
    'conjunction with collision probability Pc > 10^-4. The 14 features per timestep include: minimum range '
    '(MIN_RNG), collision probability (PC), radar cross sections of both objects (SAT1_RCS, SAT2_RCS), exclusion '
    'volumes (SAT_1_EXCL_VOL, SAT_2_EXCL_VOL), emergency reportable flag, object types for both satellites, and '
    '5 time-based features derived from TCA and CDM creation timestamps.'
)
doc.add_heading('3.2 Multi-Scale Retention Mechanism', level=2)
doc.add_paragraph(
    'The retention mechanism replaces standard self-attention with a causal decay formulation. For a query at '
    'position n and key at position i, the retention weight is defined as theta_{n-i} = (n-i)^(-gamma) for n > i '
    'and 1 for n = i, where gamma controls the decay rate. Different attention heads use different gamma values, '
    'enabling multi-scale temporal modeling. In our implementation, we use gamma in {0.9, 0.95, 0.99, 0.995}, '
    'where smaller gamma values (0.9) emphasize recent observations and larger values (0.995) retain information '
    'from earlier timesteps. The output at position n is computed as o_n = q_n * sum_i decay[n,i] * k_i * v_i, '
    'normalized by D_n = sum_i decay[n,i]. This formulation achieves O(n) complexity per layer.'
)
doc.add_heading('3.3 SwiGLU Feed-Forward Network', level=2)
doc.add_paragraph(
    'We replace the standard ReLU feed-forward network with SwiGLU from the LLaMA architecture: '
    'FFN(x) = W_2 * (SiLU(xW_1) * xW_3), where SiLU is the sigmoid linear unit. SwiGLU has been shown to '
    'outperform standard FFNs in large language models and provides smoother gradient flow, which is beneficial '
    'for the class-imbalanced collision prediction task. The expansion ratio is set to 4/3 * d_model to maintain '
    'parameter count comparable to a standard FFN.'
)
doc.add_heading('3.4 Model Architecture', level=2)
doc.add_paragraph(
    'The complete RetNet model consists of: (1) a linear input projection from 14 features to d_model = 128 '
    'dimensions, (2) learnable positional embeddings of shape (1, 25, 128), (3) 4 stacked RetNet blocks, each '
    'containing pre-LayerNorm, multi-scale retention with 4 heads, residual connection, pre-LayerNorm, SwiGLU FFN, '
    'and another residual connection, (4) a final LayerNorm, (5) last-timestep pooling, and (6) a two-layer '
    'classification head (128 -> 64 -> 1) with GELU activation and dropout. The model has 539,009 trainable '
    'parameters. The Transformer baseline follows an identical structure but replaces retention with standard '
    'causal multi-head self-attention, resulting in 543,617 parameters.'
)

